const difficultyFor = index => index < 7 ? 'easy' : index < 14 ? 'medium' : 'hard';
const sourcePolicyFor = category => category === 'dynamic_web'
  ? { primary: ['official_web'], internet: 'required' }
  : category === 'wine_md'
    ? { primary: ['wine_md_catalog'], internet: 'forbidden' }
    : { primary: ['knowledge_graph', 'documents'], internet: 'fallback' };

export const wineAiBenchmarkMvp = Object.entries(benchmarkCategories).flatMap(([category, questions]) =>
  questions.map((question, index) => ({
    id: `${category}_${String(index + 1).padStart(3, '0')}`,
    category,
    difficulty: difficultyFor(index),
    language: 'ru',
    question,
    source_policy: sourcePolicyFor(category),
    checks: {
      factual_accuracy: true,
      completeness: true,
      constraint_following: category === 'tourism' || category === 'wine_md',
      source_traceability: true,
      freshness: category === 'dynamic_web' || category === 'wine_md'
    },
    status: 'seed'
  }))
);

export default wineAiBenchmarkMvp;
